import type { MetadataRoute } from "next";
import { site } from "@/lib/site";

/**
 * Web app manifest.
 *
 * Mostly this exists so the site is installable and gets a proper name and
 * colour on an Android home screen. It is also one of the signals Chrome uses
 * to decide a site is a real destination rather than a page, and the
 * `description` and `categories` here are read by app-surface listings that
 * classic meta tags never reach.
 *
 * `id` is set explicitly. Without it the identity of the installed app is
 * derived from `start_url`, so changing the start URL later would register as
 * a different app and orphan every existing install.
 */
export default function manifest(): MetadataRoute.Manifest {
  return {
    id: "/",
    name: `${site.name} — ${site.tagline}`,
    short_name: site.shortName,
    description: site.description,
    start_url: "/",
    scope: "/",
    display: "standalone",
    background_color: "#ffffff",
    theme_color: "#0e2a5f",
    lang: "en",
    dir: "ltr",
    categories: ["education", "productivity", "books"],
    /*
     * Generated by app/icon.tsx and app/apple-icon.tsx — the same mark the
     * favicon and header logo are built from.
     *
     * Both are declared `any`, not `maskable`. Maskable promises the launcher
     * that the artwork keeps its meaning after being cropped to a circle or
     * squircle, which requires the mark to sit inside the middle 80%. Both of
     * these fill their square by design, so declaring them maskable would let
     * Android crop the mark itself. A separate padded asset is what that
     * purpose needs.
     */
    icons: [
      {
        src: "/icon",
        sizes: "96x96",
        type: "image/png",
        purpose: "any",
      },
      {
        src: "/apple-icon",
        sizes: "180x180",
        type: "image/png",
        purpose: "any",
      },
    ],
  };
}
